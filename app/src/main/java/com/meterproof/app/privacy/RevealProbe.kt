package com.meterproof.app.privacy

/**
 * اقتراح كشف منطقة واحدة بوضوح (مثل ورقة الفاتورة).
 * المصدر يقترح فقط، أما القرار فللسياسة: أي خطر أو فشل كاشف في أي مكان من الإطار يُلغي الاقتراح
 * وتُتلف الصورة، ومنطقة أكبر من الحد المسموح لا تُكشف.
 */
data class RevealProposal(val region: Region, val detail: InvoiceDetail)

/**
 * مصدر اقتراحات الكشف. يُستدعى على الإطار نفسه في الذاكرة قبل قرار السياسة.
 * أي استثناء منه يُعدّ عدم اقتراح (والصورة تبقى مجرّدة أو تُتلف حسب الكواشف).
 * لا يجوز لمن ينفذه كتابة الإطار أو أي جزء منه على التخزين.
 */
fun interface RevealProbe {
    fun propose(frame: Frame): RevealProposal?
}
